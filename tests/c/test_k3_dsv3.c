/*
 * test_k3_dsv3.c: hand cases for the dsv3 K3 c twin (docs/templates/dsv3.md, kernels.md §2-3): every rule and
 * every note with hf's pieces (tests/k3/dsv3_golden.h; ill-formed utf-8 with the python model's pieces), the
 * TOKS_CLASSES_DSV3 class tables against the doc's §2 (every code point), all strings of up to 3 atoms over a
 * representative alphabet and of 4 atoms over a smaller one (ill-formed bytes among the atoms), ill-formed bytes
 * at every position, long runs of every kind, caps 1..n with resume equivalence, guard-page geometry (no read
 * at or past len; lengths 0..255, start alignment 0..63), the parameter bits the template ignores, and the abi
 * (callee-saved registers) through toks_abicheck_call.
 *
 * Two oracles: hf 0.23.2's pieces for the golden cases (generated by tests/k3/dsv3_gen.py golden), and a
 * reference scanner restating the doc's rules over a decoded atom array (written from the prose, not from the
 * kernel's streaming code) for everything else. The outer oracle at scale is tests/k3/dsv3_run.sh on a lab host;
 * this file is the fast gate.
 */
