int main(void)
{
    build_tables();
    check_han();

    /* the golden cases: hf 0.23.2's pieces for every rule and note of docs/templates/o200k.md */
    for (size_t g = 0; g < sizeof GOLDEN / sizeof GOLDEN[0]; g++) {   /* bound: the table */
        char label[48];
        snprintf(label, sizeof label, "golden #%zu", g);
        run_case(GOLDEN[g].v, label, (const uint8_t *)GOLDEN[g].s, GOLDEN[g].len,
                 GOLDEN_ENDS + GOLDEN[g].first, GOLDEN[g].n, MAXCASE);
    }

    /* every string of 0..3 atoms over one representative per behaviour, 4 atoms over a smaller set */
    {
        static const uint32_t rep[] = {
            'A', 'a', 0x1C5, 0x2B0, 0x4E2D, 0x301, '5', ' ', '\t', 0x3000, '\r', '\n', '!', '/', '\'',
            's', 'S', 'l', 'e', 0x17F, 0x1F600, 0xE9, 0x660, 0x93E, 0x3007, 0x2E80, 0x3005, 0x16FF0
        };
        static const uint32_t small[] = { 'A', 'a', 0x4E2D, 0x301, '5', ' ', '\n', '!', '/', '\'', 's', 0x3007 };
        const size_t nr = sizeof rep / sizeof rep[0], ns = sizeof small / sizeof small[0];
        uint8_t buf[32];
        for (size_t x = 0; x < nr * nr * nr + nr * nr + nr + 1u; x++) {   /* bound: 28^3 + 28^2 + 28 + 1 */
            size_t len_atoms = x == 0u ? 0u : x <= nr ? 1u : x <= nr + nr * nr ? 2u : 3u;
            size_t idx = x == 0u ? 0u : len_atoms == 1u ? x - 1u : len_atoms == 2u ? x - 1u - nr : x - 1u - nr - nr * nr;
            uint64_t n = 0;
            for (size_t k = 0; k < len_atoms; k++) { n += utf8(rep[idx % nr], buf + n); idx /= nr; }
            for (int v = 0; v < NV; v++) { run_case(v, "rep<=3", buf, n, NULL, 0, 4); }   /* bound: NV */
        }
        for (size_t x = 0; x < ns * ns * ns * ns; x++) {                  /* bound: 12^4 */
            size_t idx = x;
            uint64_t n = 0;
            for (int k = 0; k < 4; k++) { n += utf8(small[idx % ns], buf + n); idx /= ns; }
            for (int v = 0; v < NV; v++) { run_case(v, "small4", buf, n, NULL, 0, 5); }   /* bound: NV */
        }
    }

    /* invalid utf-8: P atoms without flags -- a letter prefix, a punctuation atom, never a case atom.
     * Hand values from §2-§3 (hf cannot see invalid utf-8), checked against both the ref and the kernel. */
    {
        static const uint32_t e_ffabc[] = { 4 }, e_affb[] = { 1, 3 }, e_itc5[] = { 2, 4 }, e_xfold[] = { 4 },
                              e_xfold_nemo[] = { 1, 4 }, e_mark[] = { 2 }, e_ccbang[] = { 2 },
                              e_ffmark[] = { 3 }, e_tail[] = { 4 };
        expect1(0, "FF abc", "\xFF" "abc", 4, e_ffabc, 1);              /* the prefix of a letter run */
        expect1(0, "a FF b", "a\xFF" "b", 3, e_affb, 2);                /* a | FF b */
        expect1(0, "it' C5", "it'\xC5", 4, e_itc5, 2);                  /* a cut U+017F is no suffix */
        expect1(0, "x' U+017F", "x'\xC5\xBF", 4, e_xfold, 1);           /* the suffix 'ſ */
        expect1(1, "x' U+017F nemo", "x'\xC5\xBF", 4, e_xfold_nemo, 2); /* nemo: x | 'ſ */
        expect1(0, "U+0301", "\xCC\x81", 2, e_mark, 1);                 /* a whole mark */
        expect1(0, "CC !", "\xCC!", 2, e_ccbang, 1);                    /* a cut mark is P: CC! */
        expect1(0, "FF U+0301", "\xFF\xCC\x81", 3, e_ffmark, 1);        /* FF prefixes the mark */
        expect1(0, "! FF LF /", "!\xFF\n/", 4, e_tail, 1);              /* P run, then the tail */
    }
    {   /* every ill-formed kind at every position: kernel == ref */
        static const uint8_t salad[] = {
            'a', 0xC3, 0xA9, 'B', 0xE0, 0x80, 0x80, 'c',     /* overlong E0 80 80 */
            0xF0, 0x9F, 0x98, 'd',                            /* truncated 4-byte */
            0x80, 'E',                                         /* lone continuation */
            0xC2, 'f', '\'', 0xC5,                            /* C2 then non-continuation; ' then cut ſ */
            0xED, 0xA0, 0x80, 'g',                            /* encoded surrogate */
            0xF4, 0x90, 0x80, 0x80, 'h',                       /* above U+10FFFF */
            0xC0, 0xAF, '/', '\n', '/',                        /* overlong 2-byte, then a tail */
            0xE0, 0x9F, 0xBF, 0xCC, 0x81, 'J',                /* E0 out of range, then a mark */
            0xF0, 0x80, 0x80, 0x80, 'k', '\'', 'S'             /* overlong 4-byte, then a suffix */
        };
        both("utf8 salad", salad, sizeof salad);
        for (uint64_t cut = 0; cut <= sizeof salad; cut++) {   /* bound: salad length */
            both("salad cut", salad, cut);
            both("salad tail", salad + cut, sizeof salad - cut);
        }
        for (int x = 0x80; x < 0x100; x++) {                     /* bound: 128 bad bytes */
            const uint8_t ctx[][4] = {
                { 'a', (uint8_t)x, 'b', 0 }, { 'A', (uint8_t)x, 'B', 0 }, { (uint8_t)x, 0xCC, 0x81, 0 },
                { '\'', (uint8_t)x, 's', 0 }, { '!', (uint8_t)x, '\n', '/' }, { ' ', (uint8_t)x, 'a', 0 },
                { 'x', '\'', (uint8_t)x, 0 }, { (uint8_t)x, 0, 0, 0 }
            };
            const uint64_t ctxlen[] = { 3, 3, 3, 3, 4, 3, 3, 1 };
            for (size_t c = 0; c < sizeof ctxlen / sizeof ctxlen[0]; c++) {   /* bound: 8 contexts */
                both("bad byte", ctx[c], ctxlen[c]);
            }
        }
    }

    /* the template ignores every parameter bit but CONTR and DIGITS (docs/templates/o200k.md §1) */
    {
        static const char *soup = "Hello, world! It's 2024.\nDON'T PANIC/42\r\n  \xE4\xB8\xAD" "A's 12345 !/\n/x";
        static uint32_t e0[MAXCASE], e1[MAXCASE];
        const uint64_t len = strlen(soup);
        for (int vi = 0; vi < NV; vi++) {
            toks_tables t2 = TT[vi];
            toks_k3_args a;
            memset(&a, 0, sizeof a);
            a.text = (const uint8_t *)soup; a.len = len; a.ends = e0; a.cap = MAXCASE;
            uint64_t n0 = k3_scan(&TT[vi], &a);
            t2.tmpl_params |= TOKS_TP_LPREFIX_ANY | TOKS_TP_PUNCT_NL | TOKS_TP_WS_NL | 0xFFFFFE00u;
            memset(&a, 0, sizeof a);
            a.text = (const uint8_t *)soup; a.len = len; a.ends = e1; a.cap = MAXCASE;
            uint64_t n1 = k3_scan(&t2, &a);
            checks++;
            if (n0 != n1 || memcmp(e0, e1, (size_t)n0 * 4u) != 0) {
                fprintf(stderr, "FAIL %s: ignored parameter bits change the pieces\n", VARIANTS[vi].name);
                failures++;
            }
        }
    }

    /* guard-page geometry: deterministic text, lengths 0..255, end flush against a no-access page and
     * start right after one at every alignment 0..63 (kernels.md §1; SPEC §14.3) */
    {
        uint64_t seed = 0x4F32303030ull;
        static const uint8_t pool[] =
            "aAs'tl/!5 \t\r\n\xC3\xA9\xC5\xBF\xE4\xB8\xAD\xCC\x81\xC7\x85\xCA\xB0\xC2\xA0\xE3\x80\x80"
            "\xF0\x9F\x98\x80\x80\xFF\xC5\xE3\x80\x87\xE2\xBA\x80\xE3\x80\x85";
        uint8_t buf[256];
        for (uint64_t len = 0; len <= 255; len++) {            /* bound: 256 lengths */
            for (uint64_t i = 0; i < len; i++) {               /* bound: len */
                buf[i] = pool[guard_rng(&seed) % (sizeof pool - 1u)];
            }
            for (int where = 0; where < 2; where++) {           /* bound: 2 guard kinds */
                for (size_t off = 0; off < (where == GUARD_START ? 64u : 1u); off++) {   /* bound: 64 */
                    guard_buf g = { 0 };
                    uint8_t *p = guard_alloc(&g, (size_t)len, where, off);
                    if (!p) { fprintf(stderr, "guard_alloc failed\n"); return 2; }
                    memcpy(p, buf, (size_t)len);
                    uint64_t mc = (where == GUARD_END || off == 0u) ? MAXCASE : 1u;
                    for (int v = 0; v < NV; v++) { run_case(v, "guard", p, len, NULL, 0, mc); }   /* bound: NV */
                    guard_free(&g);
                }
            }
        }
    }

    printf("test_k3_o200k: %" PRIu64 " checks, %d failures\n", checks, failures);
    return failures ? 1 : 0;
}
