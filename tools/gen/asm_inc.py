#!/usr/bin/env python3
"""tools/gen/asm_inc.py: the asm include of include/toks.h for NASM (.asm) and GNU as (.S) callers
(docs/design.md d17, SPEC 4.1: the asm include is generated from toks.h). Every integer and string #define,
every struct's size and field offsets, and the api's function names. The C compiler evaluates every value from
toks.h itself, so the include cannot disagree with the header it came from.

    python3 tools/gen/asm_inc.py <out dir> [cc]    ->  <out>/toks.inc (NASM), <out>/toks_asm.h (cpp, for .S)

Names: a constant keeps its name (TOKS_E_OPEN); a struct gives <STRUCT>_SIZEOF and <STRUCT>_<FIELD> offsets
(toks_info.n_ids -> TOKS_INFO_N_IDS); the functions are `extern` in toks.inc (ELF names, no underscore).
"""
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def parse(h):
    consts = [(n, v.strip()) for n, v in re.findall(r"^#define (TOKS_[A-Z0-9_]+)[ \t]+([^/\n]+?)\s*(?:/\*.*)?$", h, re.M)
              if n not in ("TOKS_API", "TOKS_H")]
    structs = []
    for name, body in re.findall(r"typedef struct (toks_\w+) \{(.*?)\} \1;", h, re.S):
        body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
        fields = []
        for decl in body.split(";"):
            m = re.match(r"\s*(?:const\s+)?\w+\s*\**\s*(.+)$", decl.strip(), re.S)
            if m:
                fields += [re.sub(r"[\s*]|\[.*?\]", "", d) for d in m.group(1).split(",")]
        structs.append((name, [f for f in fields if f]))
    funcs = re.findall(r"^TOKS_API\s[^;(]*?\b(toks_\w+)\s*\(", h, re.M)
    return consts, structs, funcs


def main():
    out = sys.argv[1]
    cc = sys.argv[2] if len(sys.argv) > 2 else os.environ.get("CC", "clang")
    with open(os.path.join(ROOT, "include", "toks.h"), encoding="utf-8") as f:
        h = f.read()
    consts, structs, funcs = parse(h)
    lines = ['#include <stddef.h>', '#include <stdio.h>', '#include "toks.h"', "int main(void)", "{"]
    for n, v in consts:
        if v.startswith('"'):
            lines.append(f'    printf("s {n} %s\\n", {n});')
        else:
            lines.append(f'    printf("i {n} %lld\\n", (long long)({n}));')
    for s, fields in structs:
        lines.append(f'    printf("i {s.upper()}_SIZEOF %zu\\n", sizeof({s}));')
        for fld in fields:
            lines.append(f'    printf("i {s.upper()}_{fld.upper()} %zu\\n", offsetof({s}, {fld}));')
    lines += ["    return 0;", "}"]
    with tempfile.TemporaryDirectory() as d:
        src, exe = os.path.join(d, "g.c"), os.path.join(d, "g")
        with open(src, "w") as f:
            f.write("\n".join(lines) + "\n")
        subprocess.run([cc, "-std=c17", "-Wall", "-Werror", "-I", os.path.join(ROOT, "include"), "-o", exe, src],
                       check=True)
        vals = subprocess.run([exe], check=True, capture_output=True, text=True).stdout.splitlines()
    head = ("generated by tools/gen/asm_inc.py from include/toks.h (TOKS_VERSION {}); do not edit"
            .format(next(v.split(" ", 2)[2] for v in vals if v.startswith("s TOKS_VERSION "))))
    nasm, gas = [f"; {head}", "%ifndef TOKS_INC", "%define TOKS_INC"], [f"/* {head} */", "#ifndef TOKS_ASM_H",
                                                                    "#define TOKS_ASM_H"]
    for v in vals:
        kind, name, val = v.split(" ", 2)
        val = f'"{val}"' if kind == "s" else (f"({val})" if val.startswith("-") else val)
        nasm.append(f"%define {name} {val}")
        gas.append(f"#define {name} {val}")
    nasm += [f"extern {fn}" for fn in funcs] + ["%endif"]
    gas.append("#endif")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "toks.inc"), "w") as f:
        f.write("\n".join(nasm) + "\n")
    with open(os.path.join(out, "toks_asm.h"), "w") as f:
        f.write("\n".join(gas) + "\n")
    print(f"{out}/toks.inc, {out}/toks_asm.h: {len(vals)} values, {len(funcs)} functions")


if __name__ == "__main__":
    main()
